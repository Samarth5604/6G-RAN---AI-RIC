// is_pilot(k) — returns true if FFT bin k carries a DMRS pilot
// Pilot positions: 213, 219, 225... every 6th within 212–811, excluding DC=512
static inline bool is_pilot(int k) {
#pragma HLS INLINE
    if (k < 213 || k > 807) return false;
    if (k == 512)            return false;
    return ((k - 213) % 6 == 0);
}

// pilot_index(k) — returns index m into DMRS_RE/IM[] for pilot at bin k
// Only call after confirming is_pilot(k)==true
static inline int pilot_index(int k) {
#pragma HLS INLINE
    // Pilots below DC: m = (k - 213) / 6,  range 0..49
    // Pilots above DC: m = (k - 513) / 6 + 50, range 50..99
    if (k < 512)
        return (k - 213) / 6;
    else
        return (k - 513) / 6 + 50;
}

